#!/usr/bin/env python3
"""Revision analyses (PeerJ #147031, minor revision).

Adds, without altering the locked pipeline (independent_rewrite_analysis.py):
  R1. Complete family-level results under the PRIMARY control-prevalence rule
      (Table S1) and under the union rule (relabelled sensitivity Table S1b).
  R2. Leave-one-animal-out, Enterococcaceae statistics, lowest-P families and
      the stepwise ablation recomputed under the primary rule.
  R3. PERMANOVA sensitivity analysis that includes animal explicitly in the
      model (distance ~ animal + timepoint; sequential SS, timepoint tested
      after animal; permutations of timepoint restricted within animal).
  R4. Exact alpha-diversity P values (primary rule and undecontaminated).
  R5. Per-sample source data for Figure 3 and fecal removal range for Figure 2.
  R6. Revised Figure 3 (pooled bars + individual-sample points) and Figure 5
      (primary rule).

Usage: python3 revision_analysis.py data/otu_table2_with_taxonomy.xlsx --output-dir outputs_revision
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

import independent_rewrite_analysis as A


def write_csv(path, header, rows):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)


def _dummies(labels, sort_key):
    labels = np.asarray(labels, dtype=object)
    levels = sorted(set(labels), key=sort_key)
    return [(labels == lv).astype(float) for lv in levels[1:]]


def _hat(x):
    return x @ np.linalg.pinv(x.T @ x) @ x.T


def permanova_animal_adjusted(dist, time_labels, animals,
                              permutations=A.PERMUTATIONS, seed=A.PERMANOVA_SEED):
    """Sequential (type I) PERMANOVA: distance ~ animal + timepoint.

    The timepoint term is tested after animal. Its null distribution is
    generated by permuting timepoint labels within animal (the animal term and
    its sum of squares are unchanged by such permutations).
    """
    n = len(time_labels)
    c = np.eye(n) - np.ones((n, n)) / n
    g = -0.5 * c @ (np.asarray(dist) ** 2) @ c
    ss_total = float(np.trace(g))
    one = np.ones((n, 1))
    a_cols = _dummies(animals, lambda v: int(v))
    x_animal = np.column_stack([one] + [col[:, None] for col in a_cols])
    h_animal = _hat(x_animal)
    ss_animal = float(np.trace(h_animal @ g))
    rank_animal = np.linalg.matrix_rank(x_animal)

    def stat(tl):
        t_cols = _dummies(tl, lambda v: v)
        x_full = np.column_stack([x_animal] + [col[:, None] for col in t_cols])
        h_full = _hat(x_full)
        ss_full = float(np.trace(h_full @ g))
        df_t = np.linalg.matrix_rank(x_full) - rank_animal
        df_res = n - np.linalg.matrix_rank(x_full)
        ss_t = ss_full - ss_animal
        ss_res = ss_total - ss_full
        return (ss_t / df_t) / (ss_res / df_res), ss_t, ss_res, df_t, df_res

    f_obs, ss_t, ss_res, df_t, df_res = stat(np.asarray(time_labels, dtype=object))
    rng = np.random.RandomState(seed)
    tl = np.asarray(time_labels, dtype=object)
    strata = np.asarray(animals, dtype=object)
    idx = [np.flatnonzero(strata == s) for s in sorted(set(strata), key=int)]
    exceed = 0
    for _ in range(permutations):
        perm = tl.copy()
        for ii in idx:
            v = perm[ii].copy()
            rng.shuffle(v)
            perm[ii] = v
        exceed += int(stat(perm)[0] >= f_obs - 1e-12)
    return dict(pseudo_F=f_obs, R2_time=ss_t / ss_total, R2_animal=ss_animal / ss_total,
                partial_R2_time=ss_t / (ss_t + ss_res), df_time=int(df_t), df_resid=int(df_res),
                p=(exceed + 1) / (permutations + 1), exceedances=exceed)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("otu_workbook", type=Path)
    ap.add_argument("--output-dir", type=Path, default=Path("outputs_revision"))
    args = ap.parse_args()
    out = args.output_dir
    out.mkdir(parents=True, exist_ok=True)
    summary = {}

    data = A.load_otu_workbook(args.otu_workbook)
    info = data.sample_info
    controls = [s.index for s in info if s.is_control]
    baseline = [s.index for s in info if s.is_baseline]
    primary = [s.index for s in info if s.is_primary_lymph]
    fecal = [s.index for s in info if s.sample_type == "FB"]
    balf = [s.index for s in info if s.sample_type == "BALF"]
    post_all = [s.index for s in info if s.sample_type == "lymph" and s.timepoint in {4, 8, 12, 24}]
    biological = primary + fecal + balf

    prev, prev_p, prev_q = A.prevalence_screen(data, controls, biological)
    cat = np.asarray([bool(g) and g.lower() in A.CONTAMINANT_GENERA_LOWER for g in data.genus])
    rules = {"prevalence": prev, "catalogue": cat, "union": prev | cat, "intersection": prev & cat}

    # R1 + R2 -----------------------------------------------------------------
    for rule in ("prevalence", "union"):
        da = A.family_da(data, rules[rule], primary, include_animal=True)
        order = np.argsort(da["p"], kind="mergesort")
        write_csv(out / f"S1_families_{rule}.csv",
                  ["family", "F", "p", "BH_FDR", "FDR_significant"],
                  [(da["family"][i], da["F"][i], da["p"][i], da["q"][i],
                    "Yes" if da["q"][i] < 0.05 else "No") for i in order])
        e = A.find_row(da, "Enterococcaceae")
        summary[f"familyDA_{rule}"] = dict(
            n_families=int(len(da["family"])), n_fdr_sig=int(np.sum(da["q"] < 0.05)),
            df=(da["df_num"], da["df_den"]),
            ent_F=float(da["F"][e]), ent_p=float(da["p"][e]), ent_q=float(da["q"][e]),
            lowest4=[(str(da["family"][i]), float(da["F"][i]), float(da["p"][i]), float(da["q"][i]))
                     for i in order[:4]])
        loo = []
        for animal in sorted({info[i].animal for i in primary}, key=int):
            rem = [i for i in primary if info[i].animal != animal]
            r = A.family_da(data, rules[rule], rem, include_animal=True)
            loo.append((animal, float(r["p"][A.find_row(r, "Enterococcaceae")])))
        summary[f"LOO_{rule}"] = loo
        abl = []
        for step, idx, adj in [("0_naive", baseline + post_all, False), ("1_remove_0h", post_all, False),
                               ("2_depth_qc", primary, False), ("3_animal_adjusted", primary, True)]:
            r = A.family_da(data, rules[rule], idx, include_animal=adj)
            k = A.find_row(r, "Enterococcaceae")
            abl.append(dict(step=step, n=len(idx), families=int(len(r["family"])),
                            fdr_sig=int(np.sum(r["q"] < 0.05)), ent_p=float(r["p"][k]),
                            df=(r["df_num"], r["df_den"])))
            if rule == "prevalence":
                o = np.argsort(r["p"], kind="mergesort")
                write_csv(out / f"S5_ablation_{step}_prevalence.csv",
                          ["family", "F", "p", "BH_FDR", "FDR_significant"],
                          [(r["family"][i], r["F"][i], r["p"][i], r["q"][i],
                            "Yes" if r["q"][i] < 0.05 else "No") for i in o])
        summary[f"ablation_{rule}"] = abl
        if rule == "prevalence":
            # Figure 5 source (primary rule)
            e = A.find_row(da, "Enterococcaceae")
            rows = []
            for pos, si in enumerate(primary):
                rows.append((info[si].sample_id, info[si].animal, info[si].timepoint,
                             int(da["counts"][e][pos]), float(da["clr"][e][pos])))
            rows.sort(key=lambda r: (int(r[1]), int(r[2])))
            write_csv(out / "Fig5_enterococcaceae_trajectory_prevalence.csv",
                      ["sample_id", "animal", "timepoint_h", "raw_family_count", "clr_value"], rows)
            fig, ax = plt.subplots(figsize=(7.2, 4.8))
            for animal in sorted({r[1] for r in rows}, key=int):
                sel = [r for r in rows if r[1] == animal]
                ax.plot([r[2] for r in sel], [r[4] for r in sel], marker="o", lw=1.4, label=f"Animal {animal}")
            ax.set_xticks([4, 8, 12, 24])
            ax.set_xlabel("Time after CLP (h)")
            ax.set_ylabel("Enterococcaceae CLR abundance")
            ax.spines[["top", "right"]].set_visible(False)
            ax.legend(frameon=False, ncol=3)
            ax.set_title("Enterococcaceae, 4–24 h after CLP (control-prevalence rule)")
            fig.tight_layout()
            for ext in ("png", "pdf"):
                fig.savefig(out / f"Figure5_enterococcaceae.{ext}", dpi=300)
            plt.close(fig)

    # R3 + R4 -----------------------------------------------------------------
    labels = [info[i].timepoint for i in primary]
    animals = [info[i].animal for i in primary]
    alpha_order = sorted(primary, key=lambda i: (int(info[i].animal), int(info[i].timepoint)))
    a_groups = [info[i].timepoint for i in alpha_order]
    a_animals = [info[i].animal for i in alpha_order]
    perm_rows = []
    for rule, mask in rules.items():
        d = A.bray_curtis_matrix(A.family_relative_abundance(data, mask, primary))
        f0, r20, p0, _ = A.restricted_permanova(d, labels, animals)
        adj = permanova_animal_adjusted(d, labels, animals)
        perm_rows.append((rule, f0, r20, p0, adj["pseudo_F"], adj["R2_time"], adj["partial_R2_time"],
                          adj["R2_animal"], adj["df_time"], adj["df_resid"], adj["p"]))
        summary[f"permanova_{rule}"] = dict(timepoint_only=dict(F=f0, R2=r20, p=p0), animal_adjusted=adj)
    write_csv(out / "S7_permanova_animal_adjusted.csv",
              ["rule", "timepoint_only_pseudoF", "timepoint_only_R2", "timepoint_only_p",
               "adj_pseudoF_time", "adj_R2_time", "adj_partialR2_time", "R2_animal",
               "df_time", "df_resid", "adj_p_time"], perm_rows)

    def alpha_p(mask):
        sh, ri = A.alpha_diversity_test(data.counts, alpha_order, mask)
        fs, ps, *_ = A.nested_f_test_matrix(sh[None, :], a_groups, a_animals, True)
        fr, pr, *_ = A.nested_f_test_matrix(ri[None, :], a_groups, a_animals, True)
        return dict(shannon_F=float(fs[0]), shannon_p=float(ps[0]), richness_F=float(fr[0]), richness_p=float(pr[0]))
    summary["alpha_prevalence"] = alpha_p(prev)
    summary["alpha_undecontaminated"] = alpha_p(np.zeros_like(prev))

    # R5 + R6 -----------------------------------------------------------------
    gut = np.asarray([bool(g) and g.lower() in A.GUT_GENERA_LOWER for g in data.genus])
    per = []
    for grp, idx in (("0 h lymph", baseline), ("Negative controls", controls)):
        for i in idx:
            tot = data.counts[:, i].sum()
            per.append((grp, info[i].sample_id, int(tot),
                        100 * data.counts[gut, i].sum() / tot, 100 * data.counts[cat, i].sum() / tot))
    write_csv(out / "Fig3_per_sample_composition.csv",
              ["group", "sample_id", "reads", "gut_associated_pct", "reagent_catalogue_pct"], per)
    summary["fig3_per_sample"] = per
    summary["fecal_removed_pct"] = {r: 100 * A.removed_read_fraction(data, m, fecal) for r, m in rules.items()}

    groups = ["0 h lymph", "Negative controls"]
    pooled = {}
    for grp, idx in (("0 h lymph", baseline), ("Negative controls", controls)):
        c = data.counts[:, idx]
        pooled[grp] = (100 * c[gut].sum() / c.sum(), 100 * c[cat].sum() / c.sum())
    fig, axes = plt.subplots(1, 2, figsize=(9.0, 4.3))
    cols = {"0 h lymph": "#4C72B0", "Negative controls": "#8C8C8C"}
    for ax, (k, title) in zip(axes, ((0, "Gut-associated genera"), (1, "Reagent/environment catalog genera"))):
        x = np.arange(2)
        ax.bar(x, [pooled[g][k] for g in groups], color=[cols[g] for g in groups], alpha=0.45,
               width=0.6, label="Pooled fraction")
        rng = np.random.RandomState(0)
        for xi, g in enumerate(groups):
            vals = [r[3 + k] for r in per if r[0] == g]
            ax.scatter(xi + rng.uniform(-0.12, 0.12, len(vals)), vals, color=cols[g], edgecolor="black",
                       linewidth=0.5, s=28, zorder=3)
        ax.set_xticks(x)
        ax.set_xticklabels([f"{g}\n(pooled {pooled[g][k]:.2f}%)" for g in groups])
        ax.set_ylabel("Reads (%)")
        ax.set_title(title, fontsize=10)
        ax.spines[["top", "right"]].set_visible(False)
    fig.text(0.5, 0.005, "Bars: pooled read fraction per group; points: individual samples "
             "(0 h lymph n = 5; negative controls n = 6).", ha="center", fontsize=8)
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    for ext in ("png", "pdf"):
        fig.savefig(out / f"Figure3_baseline_composition.{ext}", dpi=300)
    plt.close(fig)
    summary["fig3_pooled"] = pooled

    (out / "revision_summary.json").write_text(json.dumps(summary, indent=2, default=str), encoding="utf-8")
    print(json.dumps(summary, indent=1, default=str))


if __name__ == "__main__":
    main()
